export const ICON_NAMES = Object.keys(ICONS);

function Icon({ name, size = 20, strokeWidth, className = '', title, ...rest }) {
  const shapes = ICONS[name];
  if (!shapes) return null;
  // Keep the stroke between 1.5 and 2 at every size: small icons get a slightly heavier line.
  const stroke = strokeWidth || (size <= 18 ? 2 : 1.75);
  return (
    <svg
      className={`bh-icon ${className}`.trim()}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={stroke}
      strokeLinecap="round"
      strokeLinejoin="round"
      focusable="false"
      role={title ? 'img' : undefined}
      aria-hidden={title ? undefined : 'true'}
      aria-label={title || undefined}
      {...rest}
    >
      {shapes}
    </svg>
  );
}

